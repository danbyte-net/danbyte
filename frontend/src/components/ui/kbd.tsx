import { cn } from "@/lib/utils"

// shadcn/ui Kbd (radix-vega). One change from the registry copy: the tooltip
// chip here only inverts on light - on dark it steps up to `bg-secondary`
// (see tooltip.tsx) - so inside a dark tooltip the key keeps the chip's own
// text colour instead of the registry's inverted `text-background`.
function Kbd({ className, ...props }: React.ComponentProps<"kbd">) {
  return (
    <kbd
      data-slot="kbd"
      className={cn(
        "pointer-events-none inline-flex h-5 w-fit min-w-5 items-center justify-center gap-1 rounded-sm bg-muted px-1 font-sans text-xs font-medium text-muted-foreground select-none in-data-[slot=tooltip-content]:bg-background/20 in-data-[slot=tooltip-content]:text-background dark:in-data-[slot=tooltip-content]:bg-background/40 dark:in-data-[slot=tooltip-content]:text-secondary-foreground [&_svg:not([class*='size-'])]:size-3",
        className
      )}
      {...props}
    />
  )
}

function KbdGroup({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <kbd
      data-slot="kbd-group"
      className={cn("inline-flex items-center gap-1", className)}
      {...props}
    />
  )
}

export { Kbd, KbdGroup }
